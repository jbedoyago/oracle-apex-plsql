SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY, DEPARTMENT_NAME, SYSDATE AS CURRENT_DATE FROM EMPLOYEES E
INNER JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME, SALARY, SYSDATE AS CURRENT_DATE FROM EMPLOYEES E WHERE SALARY > (SELECT AVG(SALARY) FROM EMPLOYEES)
ORDER BY SALARY DESC
FETCH FIRST 10 ROWS ONLY;

SELECT D.DEPARTMENT_NAME, COUNT(E.EMPLOYEE_ID) AS NUM_EMPLOYEES, SYSDATE AS CURRENT_DATE FROM DEPARTMENTS D
LEFT JOIN EMPLOYEES E ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME;

SELECT E.FIRST_NAME ||' '|| E.LAST_NAME AS EMPLOYEE_NAME, E.SALARY, D.DEPARTMENT_NAME, L.CITY FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN LOCATIONS L ON D.LOCATION_ID = L.LOCATION_ID;

CREATE OR REPLACE TRIGGER TRG_SALARY_CHANGE
BEFORE UPDATE OF SALARY ON EMPLOYEES FOR EACH ROW
WHEN (NEW.SALARY <> OLD.SALARY)
BEGIN
	INSERT INTO JOB_HISTORY (EMPLOYEE_ID, START_DATE, END_DATE, JOB_ID, DEPARTMENT_ID)
	VALUES (:OLD.EMPLOYEE_ID, SYSDATE, SYSDATE, :OLD.JOB_ID, :OLD.DEPARTMENT_ID);
END;

CREATE MATERIALIZED VIEW MV_AVGSALARY_DEPT
	BUILD IMMEDIATE
	REFRESH START WITH SYSDATE
	NEXT SYSDATE +1
	AS SELECT DEPARTMENT_ID, AVG(SALARY) AS AVG_SALARY
	FROM EMPLOYEES
	GROUP BY DEPARTMENT_ID;

CREATE OR REPLACE PROCEDURE UPDATE_SALARY_DEPT (P_DEPARTMENT_ID IN EMPLOYEES.DEPARTMENT_ID%TYPE, P_PERCENTAGE IN NUMBER)
AS
BEGIN
	UPDATE EMPLOYEES SET SALARY = SALARY * (1 + P_PERCENTAGE / 100)
	WHERE DEPARTMENT_ID = P_DEPARTMENT_ID;
	COMMIT;
END;
