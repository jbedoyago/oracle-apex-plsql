CREATE OR REPLACE FUNCTION CALCULATE_BONUS(
	F_EMPLOYEE_ID NUMBER
)	RETURN NUMBER IS
		V_SALARY_NUMBER;
		V_HIRE_DATE DATE;
		V_YEARS NUMBER;
		V_BONUS NUMBER;
BEGIN
	SELECT SALARY, HIRE_DATE INTO V_SALARY, V_HIRE_DATE FROM EMPLOYEES WHERE EMPLOYEE_ID = F_EMPLOYEE_ID;
	V_YEARS := EXTRACT(YEAR FROM SYSDATE) - EXTRACT(YEAR FROM V_HIRE_DATE);
	V_BONUS := V_SALARY * (V_YEARS * 0.05);
	RETURN V_BONUS;
END CALCULATE_BONUS;
/

CREATE OR REPLACE PROCEDURE INCREASE_SALARY (P_DEPARTMENT_ID NUMBER) IS
	CURSOR INC_CURSOR IS
	SELECT EMPLOYEE_ID, SALARY, HIRE_DATE FROM EMPLOYEES WHERE DEPARTMENT_ID = P_DEPARTMENT_ID;
	V_EMPLOYEE_ID EMPLOYEES.EMPLOYEE_ID%TYPE;
	V_SALARY EMPLOYEES.SALARY%TYPE;
	V_HIRE_DATE EMPLOYEES.HIRE_DATE%TYPE;
	V_YEARS NUMBER;
BEGIN
	OPEN INC_CURSOR;
	LOOP
		FETCH INC_CURSOR INTO V_EMPLOYEE_ID, V_SALARY, V_HIRE_DATE;
		EXIT WHEN INC_CURSOR%NOTFOUND;

		V_YEARS := EXTRACT(YEAR FROM SYSDATE) - EXTRACT(YEAR FROM V_HIRE_DATE);

		IF V_YEARS > 2 THEN
			UPDATE EMPLOYEES
			SET SALARY = SALARY * 1.10 WHERE EMPLOYEE_ID = V_EMPLOYEE_ID;
		END IF;
	END LOOP;
	CLOSE INC_CURSOR;

	COMMIT;
END INCREASE_SALARY;
/

CREATE OR REPLACE PROCEDURE DEPT_EMP_STATS(
	P_DEPARTMENT_ID IN EMPLOYEES.DEPARTMENT_ID%TYPE,
	P_EMPLOYEES_COUNT OUT NUMBER,
	P_TOTAL_SALARY OUT NUMBER
) AS
BEGIN
	SELECT COUNT(*), NVL(SUM(SALARY), 0)
	INTO P_EMPLOYEES_COUNT, P_TOTAL_SALARY FROM EMPLOYEES WHERE DEPARTMENT_ID = P_DEPARTMENT_ID;
END;
/
DECLARE
	V_EMPLOYEES_COUNT NUMBER;
	V_TOTAL_SALARY NUMBER;
